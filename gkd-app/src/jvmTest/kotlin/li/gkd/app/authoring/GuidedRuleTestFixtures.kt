fun testNode(
    id: Int,
    pid: Int,
    name: String? = null,
    viewId: String? = null,
    text: String? = null,
    desc: String? = null,
    clickable: Boolean = false,
    longClickable: Boolean = false,
    childCount: Int = 0,
    index: Int = 0,
    depth: Int = 0,
    bounds: GuidedRecordingBounds = GuidedRecordingBounds(0, 0, 100, 100),
): NodeInfo = NodeInfo(
    id = id,
    pid = pid,
    idQf = false,
    textQf = false,
    attr = AttrInfo(
        id = viewId,
        vid = viewId?.substringAfterLast('/'),
        name = name,
        text = text,
        desc = desc,
        clickable = clickable,
        focusable = clickable,
        checkable = false,
        checked = null,
        editable = false,
        longClickable = longClickable,
        visibleToUser = true,
        left = bounds.left,
        top = bounds.top,
        right = bounds.right,
        bottom = bounds.bottom,
        width = bounds.right - bounds.left,
        height = bounds.bottom - bounds.top,
        childCount = childCount,
        index = index,
        depth = depth,
    ),
)

